 CREATE DATABASE IF NOT EXISTS sia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
 USE sia;

CREATE TABLE IF NOT EXISTS leads (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(160),
  service VARCHAR(120),
  message TEXT,
  source VARCHAR(60),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS security_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  property_type VARCHAR(20) NOT NULL,
  location VARCHAR(120) NOT NULL,
  qty VARCHAR(40),
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(160),
  message TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS web_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  website_type VARCHAR(40) NOT NULL,
  business VARCHAR(120) NOT NULL,
  goal VARCHAR(200),
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(160),
  message TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS plan_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_name VARCHAR(80) NOT NULL,
  business_type VARCHAR(120) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  email VARCHAR(160),
  message TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS testimonials (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  text TEXT NOT NULL,
  rating TINYINT,
  is_placeholder TINYINT(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS blog_posts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  slug VARCHAR(180) NOT NULL,
  excerpt VARCHAR(240),
  content MEDIUMTEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
